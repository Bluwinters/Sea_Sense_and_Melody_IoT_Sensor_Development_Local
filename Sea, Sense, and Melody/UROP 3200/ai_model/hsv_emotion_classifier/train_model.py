import os
import pickle
import time
import numpy as np
import torch
import torch.nn as nn
from sklearn.preprocessing import StandardScaler

from mood_model import GRUMoodClassifier
from emotion_profiles import NUM_CLASSES, INPUT_DIM, WINDOW_SIZE

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
TOY_DIR = os.path.join(BASE_DIR, "toy_dataset")
MODELS_DIR = os.path.join(BASE_DIR, "trained_model")
os.makedirs(MODELS_DIR, exist_ok=True)

# ---------------------------------------------------------------------------
# Hyperparameters
# ---------------------------------------------------------------------------
BATCH_SIZE = 256
EPOCHS = 20
LR = 1e-3


def load_data():
    """
    Load synthetic dataset from toy_dataset/.

    Returns:
        X: Feature array of shape (N, 12, 17)
        y: Label array of shape (N,)
    """
    print("[INFO] Loading data...")
    start = time.time()

    X = np.load(os.path.join(TOY_DIR, "X_seq.npy"))
    y = np.load(os.path.join(TOY_DIR, "y_labels.npy"))

    elapsed = time.time() - start
    print(f"[INFO] Data loaded in {elapsed:.2f}s")
    print(f"[INFO] X shape: {X.shape}, dtype: {X.dtype}")
    print(f"[INFO] y shape: {y.shape}, dtype: {y.dtype}")
    print(f"[INFO] Feature range: [{X.min():.4f}, {X.max():.4f}]")
    print(f"[INFO] NaN count: {np.isnan(X).sum()}")

    # Print class distribution
    class_counts = np.bincount(y, minlength=NUM_CLASSES)
    print(f"[INFO] Class distribution:")
    for i in range(NUM_CLASSES):
        print(f"        Class {i:2d}: {class_counts[i]:6d} samples ({class_counts[i]/len(y)*100:.1f}%)")

    return X, y


def main():
    """
    Main training pipeline:
        1. Load and normalize data
        2. Split into train/validation sets
        3. Train GRU classifier with cross-entropy loss
        4. Save model weights and scaler
    """
    print("\n" + "=" * 70)
    print("  HSV EMOTION CLASSIFIER — MODEL TRAINING")
    print("  Author: KUANG, Haozhe | HKUST")
    print("=" * 71)

    # Print hyperparameters
    print("\n[HYPERPARAMETERS]")
    print(f"  Batch size:            {BATCH_SIZE}")
    print(f"  Epochs:                {EPOCHS}")
    print(f"  Learning rate:         {LR}")
    print(f"  Input dimension:       {INPUT_DIM}")
    print(f"  Window size:           {WINDOW_SIZE}")
    print(f"  Number of classes:     {NUM_CLASSES}")
    print(f"  Model:                 GRUMoodClassifier")
    print(f"  Device:                {'cuda' if torch.cuda.is_available() else 'cpu'}")

    # Load data
    X, y = load_data()
    N, T, D = X.shape

    # Standard scaling on flattened features
    print("\n[PREPROCESSING]")
    print("[INFO] Applying StandardScaler...")
    scaler_start = time.time()

    scaler = StandardScaler()
    X_flat = X.reshape(-1, D)
    X_scaled_flat = scaler.fit_transform(X_flat)
    X_scaled = X_scaled_flat.reshape(N, T, D)

    scaler_elapsed = time.time() - scaler_start
    print(f"[INFO] Scaling complete in {scaler_elapsed:.2f}s")
    print(f"[INFO] Scaler mean (first 5 dims): {scaler.mean_[:5]}")
    print(f"[INFO] Scaler std  (first 5 dims): {np.sqrt(scaler.var_[:5])}")

    # Shuffle and split 85/15
    print("\n[DATA SPLIT]")
    idx = np.arange(N)
    np.random.shuffle(idx)
    split = int(0.85 * N)
    X_train = X_scaled[idx[:split]]
    y_train = y[idx[:split]]
    X_val = X_scaled[idx[split:]]
    y_val = y[idx[split:]]

    print(f"[INFO] Training samples:   {X_train.shape[0]:,} ({split/N*100:.1f}%)")
    print(f"[INFO] Validation samples: {X_val.shape[0]:,} ({(N-split)/N*100:.1f}%)")

    # Verify class balance in splits
    train_counts = np.bincount(y_train, minlength=NUM_CLASSES)
    val_counts = np.bincount(y_val, minlength=NUM_CLASSES)
    print(f"[INFO] Train class range: [{train_counts.min()}, {train_counts.max()}]")
    print(f"[INFO] Val class range:   [{val_counts.min()}, {val_counts.max()}]")

    # Device setup
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"\n[HARDWARE]")
    print(f"[INFO] Using device: {device}")
    if device.type == 'cuda':
        print(f"[INFO] GPU: {torch.cuda.get_device_name(0)}")
        print(f"[INFO] Memory: {torch.cuda.get_device_properties(0).total_memory / 1e9:.1f} GB")

    # Model initialization
    print("\n[MODEL INITIALIZATION]")
    model = GRUMoodClassifier(num_classes=NUM_CLASSES).to(device)

    total_params = sum(p.numel() for p in model.parameters())
    trainable_params = sum(p.numel() for p in model.parameters() if p.requires_grad)
    print(f"[INFO] Total parameters:     {total_params:,}")
    print(f"[INFO] Trainable parameters: {trainable_params:,}")
    print(f"[INFO] Model architecture:")
    print(model)

    # Convert to tensors
    X_train_t = torch.tensor(X_train, dtype=torch.float32).to(device)
    y_train_t = torch.tensor(y_train, dtype=torch.long).to(device)
    X_val_t = torch.tensor(X_val, dtype=torch.float32).to(device)
    y_val_t = torch.tensor(y_val, dtype=torch.long).to(device)

    criterion = nn.CrossEntropyLoss()
    optimizer = torch.optim.Adam(model.parameters(), lr=LR)

    # Training header
    print("\n" + "=" * 95)
    print("  TRAINING PROGRESS")
    print("=" * 99)
    print(f"  {'Epoch':<6} {'Batch Loss':<12} {'Avg Loss':<10} "
          f"{'Train Acc':<11} {'Val Acc':<11} {'LR':<10} {'Time':<8}")
    print("-" * 93)

    # Training loop
    best_val_acc = 0.0
    best_epoch = 0
    training_start = time.time()

    for epoch in range(EPOCHS):
        epoch_start = time.time()
        model.train()

        perm = torch.randperm(X_train_t.size(0))
        total_loss = 0.0
        correct_train = 0
        total_train = 0
        batch_count = 0

        for i in range(0, X_train_t.size(0), BATCH_SIZE):
            batch_start = time.time()
            bi = perm[i:i + BATCH_SIZE]
            xb = X_train_t[bi]
            yb = y_train_t[bi]

            optimizer.zero_grad()
            out = model(xb)
            loss = criterion(out, yb)
            loss.backward()
            optimizer.step()

            # Track training accuracy
            _, predicted = torch.max(out, 1)
            correct_train += (predicted == yb).sum().item()
            total_train += yb.size(0)

            total_loss += loss.item() * xb.size(0)
            batch_count += 1

            batch_time = time.time() - batch_start

            # Print every 20 batches
            if batch_count % 20 == 0 or i + BATCH_SIZE >= X_train_t.size(0):
                batch_acc = (predicted == yb).float().mean().item()
                print(f"  [{epoch+1:02d}/{EPOCHS}] Batch {batch_count:3d}/{len(range(0, X_train_t.size(0), BATCH_SIZE))} "
                      f"| loss={loss.item():.4f} | batch_acc={batch_acc:.4f} | {batch_time:.2f}s/batch")

        # End of epoch metrics
        avg_loss = total_loss / X_train_t.size(0)
        train_acc = correct_train / total_train

        # Validation accuracy
        model.eval()
        with torch.no_grad():
            val_out = model(X_val_t)
            val_pred = val_out.argmax(1)
            val_acc = (val_pred == y_val_t).float().mean().item()

            # Per-class validation accuracy
            val_class_correct = np.zeros(NUM_CLASSES)
            val_class_total = np.zeros(NUM_CLASSES)
            for c in range(NUM_CLASSES):
                mask = (y_val_t.cpu().numpy() == c)
                val_class_total[c] = mask.sum()
                val_class_correct[c] = (val_pred.cpu().numpy()[mask] == c).sum()

        epoch_time = time.time() - epoch_start
        current_lr = optimizer.param_groups[0]['lr']

        print(f"  {'─' * 91}")
        print(f"  {epoch+1:<6} {total_loss/batch_count:<12.4f} {avg_loss:<10.4f} "
              f"{train_acc:<11.4f} {val_acc:<11.4f} "
              f"{current_lr:<10.2e} {epoch_time:<8.2f}s")

        # Print per-class accuracy every 5 epochs
        if (epoch + 1) % 5 == 0 or epoch == 0:
            print(f"  [Per-Class Validation Accuracy]")
            for c in range(NUM_CLASSES):
                if val_class_total[c] > 0:
                    ca = val_class_correct[c] / val_class_total[c]
                    print(f"    Class {c:2d}: {ca:.4f} ({int(val_class_correct[c])}/{int(val_class_total[c])})")

        # Track best model
        if val_acc > best_val_acc:
            best_val_acc = val_acc
            best_epoch = epoch + 1
            torch.save(model.state_dict(), os.path.join(MODELS_DIR, "gru_mood_model.pth"))
            print(f"  >>> New best model saved (val_acc={val_acc:.4f})")

        print(f"  {'─' * 83}")

    total_time = time.time() - training_start
    print("\n" + "=" * 57)
    print("  TRAINING COMPLETE")
    print("=" * 59)
    print(f"  Total training time: {total_time:.1f}s ({total_time/60:.1f} min)")
    print(f"  Best validation accuracy: {best_val_acc:.4f} ({best_val_acc*100:.2f}%)")
    print(f"  Best epoch: {best_epoch}")

    # Save artifacts
    print("\n[SAVING ARTIFACTS]")
    model_path = os.path.join(MODELS_DIR, "gru_mood_model.pth")
    scaler_path = os.path.join(MODELS_DIR, "scaler.pkl")

    # Save best model again (confirm)
    torch.save(model.state_dict(), model_path)
    with open(scaler_path, "wb") as f:
        pickle.dump(scaler, f)

    model_size_mb = os.path.getsize(model_path) / (1024 * 1024)
    scaler_size_kb = os.path.getsize(scaler_path) / 1024

    print(f"[INFO] Model saved:  {model_path} ({model_size_mb:.2f} MB)")
    print(f"[INFO] Scaler saved: {scaler_path} ({scaler_size_kb:.1f} KB)")

    # Final summary
    print("\n" + "=" * 53)
    print("  FINAL SUMMARY")
    print("=" * 53)
    print(f"  Dataset:          {N:,} sequences")
    print(f"  Train/Val split:  {split:,} / {N-split:,}")
    print(f"  Epochs trained:   {EPOCHS}")
    print(f"  Best val acc:     {best_val_acc:.4f}")
    print(f"  Model params:     {total_params:,}")
    print(f"  Output dir:       {MODELS_DIR}")
    print("=" * 54)
    print("[INFO] Training completed successfully.")


if __name__ == "__main__":
    main()